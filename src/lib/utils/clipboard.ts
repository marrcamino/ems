/**
 * Puts text on the clipboard, and says whether it worked. EMS runs over
 * plain http on the office network, where browsers do not offer
 * `navigator.clipboard`, so it falls back to the older copy command.
 */
export async function copyText(text: string) {
  try {
    if (navigator.clipboard) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // Falls through to the older command.
  }

  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.append(area);
  area.select();
  try {
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    area.remove();
  }
}
